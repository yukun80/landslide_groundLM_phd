def input_size(size, is_last):
    """复现 domain_runtime.images_for() L102-109 的缩放规则。

    注意：128x128 的来源连最后的光学图也会被放大到 256，只有 GDCLD 光学是 512。
    """
    bound = (
        INPUT_RULES["high_resolution_edge"]
        if is_last and max(size) > INPUT_RULES["auxiliary_edge"]
        else INPUT_RULES["auxiliary_edge"]
    )
    ratio = bound / max(size)
    return tuple(
        max(INPUT_RULES["min_edge"], round(v * ratio / INPUT_RULES["round_to"]) * INPUT_RULES["round_to"])
        for v in size
    )


